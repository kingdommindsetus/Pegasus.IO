import assert from 'node:assert/strict';
const url='http://127.0.0.1:4327';
const token='__Secure-neon-auth.session_token=educator-stage';
const r=await fetch(url+'/api/auth/get-session',{headers:{Cookie:token},redirect:'manual',signal:AbortSignal.timeout(20000)});
console.log('S02_NEXT_AUTH_PROXY_SESSION',r.status);
assert.equal(r.status,200);
const all=r.headers.getSetCookie();console.log('S02_COOKIE_NAMES',all.map(c=>c.split('=')[0]));
const cache=all.find(x=>x.split('=')[0].endsWith('.session_data'));
assert.ok(cache,'Signed session cache not returned by Next route');
for(const flag of ['HttpOnly','Secure','SameSite=Lax'])assert.ok(cache.includes(flag),flag+' missing in wrapped route cookie');
console.log('S02_NEXT_WRAPPED_COOKIE_FLAGS_PASSED');
const cachedCookie=cache.split(';')[0];
const before=await fetch(url+'/secure',{headers:{Cookie:token},redirect:'manual'});
assert.equal(before.status,200);
const signOut=await fetch(url+'/api/auth/sign-out',{method:'POST',headers:{Cookie:token,Origin:url,'content-type':'application/json'},body:'{}',redirect:'manual'});
console.log('S02_NEXT_SIGNOUT',signOut.status);
assert.equal(signOut.status,200);
const after=await fetch(url+'/secure',{headers:{Cookie:token},redirect:'manual'});
assert.equal(after.status,307);
const stale=await fetch(url+'/secure',{headers:{Cookie:token+'; '+cachedCookie},redirect:'manual'});
console.log('S02_NEXT_REVOKED_SIGNED_CACHE_HTTP',stale.status);
assert.equal(stale.status,307);
console.log('S02_NEXT_LOGOUT_PROXY_PASSED',JSON.stringify({revokedTokenDenied:true,revokedCachedStatus:stale.status,provider:'isolated-local-mock'}));

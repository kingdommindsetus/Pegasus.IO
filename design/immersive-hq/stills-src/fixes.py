"""Correct wording for every office still. Keys in "fix" are line numbers in ocr.json.

Value forms: "text" (left), "^text" (centred), ">text" (right), "" (erase), or a dict
{"t": text, "q": [quad override], "font": "sans|semi|sansb|caps", "color": "#hex", "track": True, "scale": 1.0}.
"add" entries draw text where the detector found none: {"q": [x1,y1,x2,y2,x3,y3,x4,y4], "t": ...} in percent.
"""


def box(x, y, w, h, t, **kw):
    """Axis-aligned add entry: left/top/width/height in percent."""
    return {"q": [x, y, x + w, y, x + w, y + h, x, y + h], "t": t, **kw}


def at(cx, cy, w, h, t, **kw):
    """Centred add entry."""
    return box(cx - w / 2, cy - h / 2, w, h, t, **kw)


import json as _json
from pathlib import Path as _Path

OCR = _json.loads((_Path(__file__).parent / "ocr.json").read_text(encoding="utf-8"))


def erase(agent, x0, y0, x1, y1, keep=()):
    """Erase every detected line whose top-left corner falls inside this region (except `keep`)."""
    return {str(i): "" for i, r in enumerate(OCR[agent])
            if x0 <= r["q"][0] <= x1 and y0 <= r["q"][1] <= y1 and i not in keep}


def col(x, ys, texts, w, h, **kw):
    """A column of left-aligned lines at the given centre heights."""
    return [box(x, y - h / 2, w, h, t, **kw) for y, t in zip(ys, texts)]


